def helmet(p):
    p.shell('pearl',[(.760,0,.007,.011,.013),(.768,0,.007,.057,.057),
            (.792,0,.007,.091,.080),(.830,0,.002,.115,.100),
            (.887,0,-.001,.123,.108),(.932,0,-.004,.114,.101),
            (.969,0,-.006,.090,.079),(.989,0,-.007,.061,.054),
            (.998,0,-.006,.026,.024),(1,0,-.005,.004,.005)],sides=72)
    # Convex wraparound panel with a beveled bezel, rounded corners and an arched top.
    # Tool changes at the individual dome stations describe its boundaries in profile.
    for ink,ox,dy in [('ceramicRim',.0025,.0035),('rubber',.0010,.0018),('visor',0,0)]:
        a,t=np.meshgrid(np.linspace(-1.10-ox*3,1.10+ox*3,63),np.linspace(0,1,21))
        edge=np.abs(a/1.12)**3
        y=(.797+.020*edge-dy)*(1-t)+(.938-.016*edge+dy)*t
        radius=np.sqrt(np.maximum(.01,1-((y-.879)/.128)**2))
        x=(.126+ox)*np.sin(a)*radius
        z=.002+(.113-ox)*np.cos(a)*radius-.0018*(abs(t-.5)*2)**6
        p.surface(np.stack((x,y,z),axis=-1),ink)
    for s in (-1,1):
        # Cyan arcs are raised in the middle. Ear receivers have a visible dark hub.
        a=np.linspace(-1,1,29); x=s*.046+.022*a; y=.875+.010*(1-a*a)
        z=.003+.114*np.sqrt(np.maximum(0,1-(x/.126)**2))
        p.stroke('cyan',np.column_stack((x,y,z)),.0036,facets=10,smooth=False)
        p.oval('darkMetal',(s*.118,.874,-.006),(.027,.043,.044),sides=36)
        p.oval('ceramicRim',(s*.135,.874,-.006),(.010,.038,.039))
        p.ellipse('cyan',(s*.143,.874,-.006),.026,.026,.0033,side=True)
        p.oval('rubber',(s*.144,.874,-.006),(.0017,.021,.021))
        p.oval('steel',(s*.145,.874,-.006),(.0008,.011,.011))
    p.stroke('cyan',[(-.018,.838,.103),(-.009,.835,.106),(0,.834,.107),(.009,.835,.106),(.018,.838,.103)],
             [.0008,.0017,.002,.0017,.0008])


