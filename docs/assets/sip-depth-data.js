export function fullStops(id) {
  if (id === 'wine') return WINE_STOPS;
  if (id === 'beer') return BEER_STOPS;
  return null;
}

export function campusStops(campus) {
  const full = fullStops(campus.id);
  if (full) return full.map(s => ({ title: s.title, note: s.note, n: s.n, playable: true }));
  const list = JOURNEYS[campus.id] || [];
  const samples = SAMPLES[campus.id] || {};
  return list.map((s, i) => ({ ...s, n: i + 1, playable: !!samples[i + 1] }));
}

